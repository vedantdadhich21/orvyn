/**
 * Compile StrategyRegistry.sol and write the ABI and bytecode into the app.
 *
 * Run with `bun run contracts:build` from apps/web. The output file is
 * committed so the app never needs a Solidity toolchain at build or run time.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import solc from 'solc';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(here, '..', 'contracts', 'StrategyRegistry.sol');
const outPath = join(here, '..', 'src', 'lib', 'orvyn', 'strategy-registry.ts');

const source = readFileSync(sourcePath, 'utf8');
const input = {
  language: 'Solidity',
  sources: { 'StrategyRegistry.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input))) as {
  errors?: Array<{ severity: string; formattedMessage: string }>;
  contracts?: Record<
    string,
    Record<string, { abi: unknown[]; evm: { bytecode: { object: string } } }>
  >;
};

const errors = (output.errors ?? []).filter((error) => error.severity === 'error');
if (errors.length > 0) {
  for (const error of errors) console.error(error.formattedMessage);
  process.exit(1);
}

const compiled = output.contracts?.['StrategyRegistry.sol']?.['StrategyRegistry'];
if (!compiled) {
  console.error('StrategyRegistry did not compile.');
  process.exit(1);
}

const bytecode = compiled.evm.bytecode.object;
if (!bytecode) {
  console.error('StrategyRegistry compiled without bytecode.');
  process.exit(1);
}

const file = `/**
 * Generated by scripts/compile-registry.ts from contracts/StrategyRegistry.sol.
 * Do not edit by hand. Run \`bun run contracts:build\` after changing the
 * contract, and commit the result with the source.
 */

export const STRATEGY_REGISTRY_ABI = ${JSON.stringify(compiled.abi, null, 2)} as const;

/** Deployment bytecode for the compiler settings in the script. */
export const STRATEGY_REGISTRY_BYTECODE =
  '0x${bytecode}' as const;
`;

writeFileSync(outPath, file);
console.log(`Wrote ${outPath} (${compiled.abi.length} ABI entries, ${bytecode.length / 2} bytes).`);
