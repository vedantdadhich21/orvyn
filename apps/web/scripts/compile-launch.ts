/**
 * Read the Foundry artifacts and write the ABI/bytecode module the app imports.
 *
 * Run from apps/web after `forge build`:
 *
 *   bun run scripts/compile-launch.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'contracts', 'out');
const target = join(here, '..', 'src', 'lib', 'orvyn', 'launch-contracts.ts');

const artifacts = [
  ['TEST_USD', 'TestUSD.sol/TestUSD.json'],
  ['PRICE_ORACLE', 'PriceOracle.sol/PriceOracle.json'],
  ['ORVYN_EXCHANGE', 'OrvynExchange.sol/OrvynExchange.json'],
  ['TEST_STOCK', 'TestStock.sol/TestStock.json'],
  ['STRATEGY_REGISTRY_V2', 'StrategyRegistryV2.sol/StrategyRegistryV2.json'],
] as const;

const lines = [
  '/**',
  ' * Generated by scripts/compile-launch.ts from the Foundry artifacts.',
  ' * Do not edit by hand. Run `forge build` then `bun run scripts/compile-launch.ts`.',
  ' */',
  '',
];

for (const [name, path] of artifacts) {
  const artifact = JSON.parse(readFileSync(join(out, path), 'utf8')) as {
    abi: unknown[];
    bytecode: { object: string };
  };
  lines.push(`export const ${name}_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;`);
  lines.push(`export const ${name}_BYTECODE = '${artifact.bytecode.object}' as const;`);
  lines.push('');
}

writeFileSync(target, lines.join('\n'));
console.log(`wrote ${target}`);
